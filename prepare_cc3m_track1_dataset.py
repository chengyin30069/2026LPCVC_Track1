from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Convert CLIP-KD CC3M CSV (title/filepath) into Track1 dataset format."
    )
    parser.add_argument(
        "--cc3m-train-csv",
        required=True,
        help="Path to cc3m_train.csv generated by CLIP-KD src/data/gather_cc.py",
    )
    parser.add_argument(
        "--cc3m-image-root",
        required=True,
        help="Image root used when running gather_cc.py (contains train/... and val/...)",
    )
    parser.add_argument("--output-dir", default="dataset_cc3m")
    parser.add_argument("--max-pairs", type=int, default=3_000_000)
    parser.add_argument("--min-text-chars", type=int, default=6)
    parser.add_argument("--max-text-chars", type=int, default=160)
    parser.add_argument(
        "--link-mode",
        choices=["symlink", "hardlink", "copy"],
        default="symlink",
    )
    parser.add_argument("--image-prefix", default="cc3m")
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def normalize_text(text: str, min_chars: int, max_chars: int) -> str | None:
    compact = " ".join(str(text).strip().split())
    if len(compact) < min_chars:
        return None
    if len(compact) > max_chars:
        compact = compact[:max_chars].rstrip()
    return compact or None


def link_or_copy(source_path: Path, target_path: Path, mode: str) -> None:
    if target_path.exists() or target_path.is_symlink():
        target_path.unlink()
    if mode == "symlink":
        target_path.symlink_to(source_path.resolve())
    elif mode == "hardlink":
        target_path.hardlink_to(source_path.resolve())
    else:
        shutil.copy2(source_path, target_path)


def main() -> None:
    args = parse_args()

    cc3m_train_csv = Path(args.cc3m_train_csv)
    image_root = Path(args.cc3m_image_root)
    if not cc3m_train_csv.exists():
        raise FileNotFoundError(f"CC3M train CSV not found: {cc3m_train_csv}")
    if not image_root.exists():
        raise FileNotFoundError(f"CC3M image root not found: {image_root}")

    output_dir = Path(args.output_dir)
    images_dir = output_dir / "images"
    img_list_path = output_dir / "img_list.csv"
    txt_list_path = output_dir / "txt_list.csv"
    summary_path = output_dir / "summary.json"

    if output_dir.exists() and args.overwrite:
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    images_dir.mkdir(parents=True, exist_ok=True)

    text_to_id: dict[str, int] = {}
    kept_pairs = 0
    skipped_missing_image = 0
    skipped_bad_text = 0

    with (
        cc3m_train_csv.open("r", encoding="utf-8", errors="replace", newline="") as source_file,
        img_list_path.open("w", encoding="utf-8", newline="") as img_file,
        txt_list_path.open("w", encoding="utf-8", newline="") as txt_file,
    ):
        # CLIP-KD uses tab-delimited "title\tfilepath"
        reader = csv.DictReader(source_file, delimiter="\t")
        if reader.fieldnames is None or "title" not in reader.fieldnames or "filepath" not in reader.fieldnames:
            raise ValueError("Expected tab-delimited columns: title, filepath")

        img_writer = csv.writer(img_file, lineterminator="\n")
        txt_writer = csv.writer(txt_file, lineterminator="\n")
        img_writer.writerow(["Image_names", "Text_ids"])
        txt_writer.writerow(["Text_id", "Text"])

        for row in reader:
            if kept_pairs >= args.max_pairs:
                break

            caption = normalize_text(row.get("title", ""), args.min_text_chars, args.max_text_chars)
            if caption is None:
                skipped_bad_text += 1
                continue

            rel_path = str(row.get("filepath", "")).strip()
            if not rel_path:
                skipped_missing_image += 1
                continue
            src_image = image_root / rel_path
            if not src_image.exists():
                skipped_missing_image += 1
                continue

            text_id = text_to_id.get(caption)
            if text_id is None:
                text_id = len(text_to_id)
                text_to_id[caption] = text_id
                txt_writer.writerow([text_id, caption])

            image_ext = src_image.suffix.lower() if src_image.suffix else ".jpg"
            image_name = f"{args.image_prefix}_{kept_pairs:09d}{image_ext}"
            dst_image = images_dir / image_name
            link_or_copy(src_image, dst_image, args.link_mode)
            img_writer.writerow([image_name, str(text_id)])
            kept_pairs += 1

    summary = {
        "source_csv": str(cc3m_train_csv),
        "image_root": str(image_root),
        "kept_pairs": kept_pairs,
        "unique_texts": len(text_to_id),
        "skipped_missing_image": skipped_missing_image,
        "skipped_bad_text": skipped_bad_text,
        "max_pairs": args.max_pairs,
        "link_mode": args.link_mode,
    }
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()

